def write_semicolon_csv(rows: list[tuple], path: Path) -> Path:
    """Helper to write sample rows in original Chicago CSV semicolon format."""
    headers = [field.name for field in RAW_CRIME_SCHEMA.fields]
    lines = [";".join(headers)]
    for row in rows:
        formatted = []
        for idx, val in enumerate(row):
            if val is None:
                formatted.append("")
            elif headers[idx] in {"Date", "Updated On"}:
                formatted.append(val.strftime("%m/%d/%Y %I:%M:%S %p"))
            else:
                formatted.append(str(val))
        lines.append(";".join(formatted))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
